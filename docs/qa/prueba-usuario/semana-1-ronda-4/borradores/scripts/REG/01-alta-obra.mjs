import { abrir, ctx, vigilar, contarEnvios, FRONT, DIR, sleep, texto, alertas, cap, db } from './lib.mjs';
const [, , numero = '2-981-2026', nombre = 'QA4-REG Obra completa Añelo'] = process.argv;
await abrir(async (b) => {
  const c = await ctx(b, 'diego'); const p = await c.newPage(); vigilar(p, 'alta');
  const env = contarEnvios(p);
  await p.goto(`${FRONT}/obras/nueva`); await p.waitForLoadState('networkidle');
  await p.getByLabel('N.º de presupuesto').first().fill(numero);
  await p.getByLabel('Nombre del trabajo').fill(nombre);
  const of = p.getByRole('group', { name: /Presupuesto \(oferta técnica\)/ });
  await of.getByRole('button', { name: 'Pegar link' }).click();
  await of.getByLabel('Link').fill('https://drive.example/QA4-REG/oferta año 2026.pdf');
  await of.getByRole('button', { name: 'Agregar link' }).click();
  await of.getByText('quitar').waitFor();
  console.log('oferta tras link:', (await of.innerText()).replace(/\n+/g, ' | '));
  console.log('foco tras agregar link:', await p.evaluate(() => document.activeElement?.outerHTML.slice(0, 120)));
  await of.getByRole('button', { name: /quitar/i }).first().click(); await sleep(500);
  console.log('oferta tras quitar:', (await of.innerText()).replace(/\n+/g, ' | '));
  await of.locator('input[type=file]').setInputFiles(`${DIR}/oferta año 2026.pdf`);
  await of.getByText('quitar').waitFor({ timeout: 15000 });
  console.log('oferta tras archivo:', (await of.innerText()).replace(/\n+/g, ' | '));
  await p.getByLabel('Cliente').fill('QA4-REG Cliente Ñandú');
  await p.getByLabel('Planta (si aplica)').fill('Planta Añelo');
  await p.getByLabel('Responsable de obra').selectOption({ label: 'Hernán · Jefatura de Proyectos' });
  await p.getByLabel('Documento de aprobación').selectOption({ label: 'Orden de compra' });
  await p.getByLabel('N.º de OC / OT / contrato').fill('OC-REG4-001');
  const oc = p.getByRole('group', { name: /OC \/ OT \/ contrato \/ mail de aprobación/ });
  await oc.locator('input[type=file]').setInputFiles(`${DIR}/oc ñandú 01.pdf`);
  await oc.getByText('quitar').waitFor({ timeout: 15000 });
  console.log('oc tras archivo:', (await oc.innerText()).replace(/\n+/g, ' | '));
  await oc.getByRole('button', { name: /quitar/i }).first().click(); await sleep(400);
  await oc.getByRole('button', { name: 'Pegar link' }).click();
  await oc.getByLabel('Link').fill('https://drive.example/QA4-REG/oc ñandú 01.pdf');
  await oc.getByRole('button', { name: 'Agregar link' }).click();
  await oc.getByText('quitar').waitFor();
  console.log('oc final:', (await oc.innerText()).replace(/\n+/g, ' | '));
  const lk = oc.getByRole('link').first(); console.log('oc link title/href:', await lk.getAttribute('title'), await lk.getAttribute('href'));
  await p.getByLabel('Inicio previsto').fill('2026-12-01');
  await p.getByLabel('Fin previsto').fill('2027-03-31');
  await p.getByLabel('Carpeta de Drive de la obra').fill('https://drive.example/Obras 2026/QA4-REG año');
  for (const t of ['Solicitante en planta', 'Comprador']) {
    await p.getByLabel(`${t} · nombre`).fill(`QA4-REG ${t} Muñoz`);
    await p.getByLabel(`${t} · mail`).fill(`qa4reg.${t.split(' ')[0].toLowerCase()}@cliente-ejemplo.com`);
    await p.getByLabel(`${t} · teléfono`).fill('291 455-1234');
  }
  await cap(p, 'REG-ok-alta-obra-antes');
  await p.getByRole('button', { name: 'Guardar obra' }).dblclick();
  await p.waitForURL(/\/obras\/\d+$/, { timeout: 20000 }).catch(() => console.log('no navegó'));
  await sleep(1500);
  console.log('envíos:', env.filter((e) => !e.includes('adjuntos')).join(' ; '));
  console.log('url', p.url(), 'alertas', await alertas(p));
  console.log((await texto(p)).slice(0, 1600));
  await cap(p, 'REG-ok-alta-obra-ficha');
  await p.goBack(); await sleep(1200);
  console.log('tras atrás:', p.url(), 'dialogs:', await p.getByRole('dialog').allInnerTexts());
  const id = db(`select obra_id from presupuestos where numero='${numero}'`);
  console.log('DB obra', id, db(`select planta, carpeta_drive_url, fecha_inicio_prevista, fecha_fin_prevista from obras where id=${id}`));
  console.log('DB adjuntos', db(`select id, contexto, tipo, nombre, url, sujeto_type, sujeto_id from adjuntos where subido_por=1 order by id desc limit 6`).replace(/\n/g, ' || '));
});
